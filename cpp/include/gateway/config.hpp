// ============================================================================
// config.hpp —— 网关路由与中间件的配置结构
// ----------------------------------------------------------------------------
// 为什么配置这么"简陋"？
//   教学项目 + 零外部依赖 = 不做 JSON/YAML 解析。
//   Go 版本也有 DefaultConfig() 工厂函数，这里照做：
//     用户直接在代码里 DefaultConfig() 拿一份，或自己 new Config 后填字段。
//   生产级网关（APISIX / Envoy）支持热加载、文件监听，但那不是教学目标。
//
// 如果以后想加 JSON 加载怎么办？
//   这里的 Config / Route / MWConfig struct 就是现成的反序列化目标——
//   加一个 LoadJSON(path) 函数就行，struct 不需要改。
// ============================================================================

#pragma once

#include <string>
#include <vector>

namespace gateway {

// ---------------------------------------------------------------------------
// Route —— 单条路由规则
// ---------------------------------------------------------------------------
//   path        : 匹配模式，如 "/api/users" 或 "/api/users/*"
//   upstream    : 后端地址，如 "127.0.0.1:9001"（注意：不带 scheme，就是 host:port）
//   strip_prefix: 可选，网关把转发路径里的这个前缀去掉
// ---------------------------------------------------------------------------
struct Route {
    std::string path;
    std::string upstream;
    std::string strip_prefix;
};

// ---------------------------------------------------------------------------
// MWConfig —— 中间件全局开关
// ---------------------------------------------------------------------------
//   cors             : 是否加 CORS 头
//   request_log      : 是否打印请求日志
//   rate_limit_qps   : 每秒最大请求数（0 = 不限）
//   auth_header_name : 必须存在的请求头名（空 = 不检查）
// ---------------------------------------------------------------------------
struct MWConfig {
    bool        cors             = true;
    bool        request_log      = true;
    int         rate_limit_qps   = 0;
    std::string auth_header_name;
};

// ---------------------------------------------------------------------------
// Config —— 网关启动时的总配置
// ---------------------------------------------------------------------------
struct Config {
    std::string      listen = "0.0.0.0:8080";   // 默认监听 :8080
    std::vector<Route> routes;
    MWConfig         mw;
};

// ---------------------------------------------------------------------------
// DefaultConfig —— 内置默认配置（Go 版本同名同用途）
//   注册一个 "/" → "127.0.0.1:9000" 的 catch-all 路由，
//   默认开 CORS 和 RequestLog，不开限流。
// ---------------------------------------------------------------------------
Config DefaultConfig();

} // namespace gateway
